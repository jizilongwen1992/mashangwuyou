export function renderGuide(root) {
  root.innerHTML = `
  <article class="doc">
    <h1 class="hero-title">打码要求</h1>
    <p class="source">依据《安徽省水利厅关于开展 2026 年度水利水电工程专业高、中级专业技术资格评审工作的通知》第三页。</p>

    <h2>交几份</h2>
    <p>同时交 2 份：1 份原始扫描件，1 份打码隐去关键敏感信息的扫描件。</p>

    <h2>要盖住的</h2>
    <ul>
      <li>姓名</li>
      <li>单位，包括公章上的单位名称</li>
      <li>照片</li>
      <li>身份证号码</li>
      <li>本人签名</li>
    </ul>

    <h2>不要盖的</h2>
    <ul>
      <li>申报人岗位及工作内容</li>
      <li>项目规模等关键指标</li>
      <li>同单位其他人员信息</li>
      <li>其他单位及人员信息</li>
      <li>学术成果的关键内容、其他参与人员信息</li>
    </ul>

    <h2>怎么盖</h2>
    <p>通知原文允许马赛克，也允许擦除或剪切后以鲜艳颜色填充覆盖或明显标注。
       本工具用不透明实色块整块覆盖，默认黑色，审阅页可改成红、橙、黄、绿、青、蓝、紫、白。</p>
    <p>审阅时屏幕上的框是半透明的，那是为了让你核对盖住了什么；导出的打码件是实色，底下的内容完全看不见。</p>

    <div class="notice">
      <div class="notice-title">尺度是「规范、适度」</div>
      漏打和过度打码都可能被退回。他人姓名和本人姓名在同一行时，只盖本人那几个字。
    </div>

    <h2>这个工具能自动找到什么</h2>
    <p>有文字层的 PDF（Word 直接导出的诚信承诺书、论文、业绩表），能按你设置的姓名、单位、简称去查，
       位置就是字的真实位置；身份证号还会按号码的形状再兜一遍，你没填也能查出来。</p>
    <p>扫描件和图片整页都是像素，没有文字可查，要自己拖框。
       照片、公章、签名这三类无论哪种材料都得自己框——机器认不出来，不要指望它。</p>

    <p class="tail">打码要求以当年评审通知为准。本页内容仅供对照，不代替通知原文。</p>
  </article>`
}

